#!/usr/bin/env node
// Regenerates apps-script/Brand.gs from the PNGs in brand/ (run after changing a logo file).
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const files = { wordmarkWhite: 'studio-wordmark-white.png', wordmarkPurple: 'studio-wordmark-purple.png', badge: 'cdx-badge.png' };
let out = '/**\n * Brand images (generated by tools/build-brand.js from brand/*.png — do not edit by hand).\n' +
  ' * Used for the logos in the web app and as inline images in receipt emails.\n */\nvar BRAND_IMAGES = {\n';
out += Object.entries(files).map(([k, f]) => `  ${k}: '${fs.readFileSync(path.join(root, 'brand', f)).toString('base64')}'`).join(',\n');
out += '\n};\n';
fs.writeFileSync(path.join(root, 'apps-script', 'Brand.gs'), out);
console.log('Wrote apps-script/Brand.gs (' + Math.round(out.length / 1024) + ' KB)');
